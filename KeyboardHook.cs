using System.ComponentModel;
using System.Diagnostics;
using System.Runtime.InteropServices;
using System.Windows.Forms;

namespace Mouse_Macro;

public sealed class KeyboardHook : IDisposable
{
    private const int WH_KEYBOARD_LL = 13;
    private const uint LLKHF_EXTENDED = 1;
    private const uint LLKHF_INJECTED = 0x10;

    private readonly HookProc _callback;
    private readonly HashSet<int> _pressed = new();
    private readonly HashSet<int> _shortcutKeysDown = new();

    private IntPtr _hook;

    public event Action? PhysicalKeyPressed;
    public event Action? RecordShortcutPressed;
    public event Action? PlayShortcutPressed;
    public event Action<bool, int, int, bool>? KeyEventDetected;

    public Keys RecordKey { get; set; } = Keys.R;
    public Keys PlayKey { get; set; } = Keys.P;

    public KeyboardHook()
    {
        _callback = Callback;
    }

    public void Start()
    {
        if (_hook != IntPtr.Zero)
            return;

        using var process = Process.GetCurrentProcess();
        using var module = process.MainModule;

        _hook = SetWindowsHookEx(
            WH_KEYBOARD_LL,
            _callback,
            GetModuleHandle(module?.ModuleName),
            0);

        if (_hook == IntPtr.Zero)
            throw new Win32Exception(Marshal.GetLastWin32Error());
    }

    private IntPtr Callback(int code, IntPtr wParam, IntPtr lParam)
    {
        if (code >= 0)
        {
            var data = Marshal.PtrToStructure<KeyData>(lParam);

            // Ignore keyboard events generated by SendInput.
            if ((data.flags & LLKHF_INJECTED) == 0)
            {
                int key = (int)data.vkCode;
                int message = (int)wParam;

                bool down =
                    message == 0x0100 ||
                    message == 0x0104;

                bool up =
                    message == 0x0101 ||
                    message == 0x0105;

                bool extended =
                    (data.flags & LLKHF_EXTENDED) != 0;

                if (up)
                {
                    bool shortcutRelease =
                        _shortcutKeysDown.Remove(key);

                    _pressed.Remove(key);

                    if (!shortcutRelease)
                    {
                        KeyEventDetected?.Invoke(
                            false,
                            key,
                            (int)data.scanCode,
                            extended);
                    }
                }
                else if (down)
                {
                    bool first = _pressed.Add(key);

                    if (first)
                        PhysicalKeyPressed?.Invoke();

                    bool ctrl =
                        _pressed.Contains((int)Keys.ControlKey) ||
                        _pressed.Contains((int)Keys.LControlKey) ||
                        _pressed.Contains((int)Keys.RControlKey);

                    bool shift =
                        _pressed.Contains((int)Keys.ShiftKey) ||
                        _pressed.Contains((int)Keys.LShiftKey) ||
                        _pressed.Contains((int)Keys.RShiftKey);

                    bool alt =
                        _pressed.Contains((int)Keys.Menu) ||
                        _pressed.Contains((int)Keys.LMenu) ||
                        _pressed.Contains((int)Keys.RMenu);

                    if (first && ctrl && shift && alt &&
                        key == (int)RecordKey)
                    {
                        _shortcutKeysDown.Add(key);
                        RecordShortcutPressed?.Invoke();
                    }
                    else if (first && ctrl && shift && alt &&
                             key == (int)PlayKey)
                    {
                        _shortcutKeysDown.Add(key);
                        PlayShortcutPressed?.Invoke();
                    }
                    else
                    {
                        KeyEventDetected?.Invoke(
                            true,
                            key,
                            (int)data.scanCode,
                            extended);
                    }
                }
            }
        }

        return CallNextHookEx(_hook, code, wParam, lParam);
    }

    public void Dispose()
    {
        if (_hook != IntPtr.Zero)
        {
            UnhookWindowsHookEx(_hook);
            _hook = IntPtr.Zero;
        }

        _pressed.Clear();
        _shortcutKeysDown.Clear();
    }

    [StructLayout(LayoutKind.Sequential)]
    private struct KeyData
    {
        public uint vkCode;
        public uint scanCode;
        public uint flags;
        public uint time;
        public IntPtr extraInfo;
    }

    private delegate IntPtr HookProc(
        int code,
        IntPtr wParam,
        IntPtr lParam);

    [DllImport("user32.dll", SetLastError = true)]
    private static extern IntPtr SetWindowsHookEx(
        int id,
        HookProc proc,
        IntPtr module,
        uint thread);

    [DllImport("user32.dll")]
    [return: MarshalAs(UnmanagedType.Bool)]
    private static extern bool UnhookWindowsHookEx(
        IntPtr hook);

    [DllImport("user32.dll")]
    private static extern IntPtr CallNextHookEx(
        IntPtr hook,
        int code,
        IntPtr wParam,
        IntPtr lParam);

    [DllImport("kernel32.dll", CharSet = CharSet.Auto)]
    private static extern IntPtr GetModuleHandle(
        string? name);
}